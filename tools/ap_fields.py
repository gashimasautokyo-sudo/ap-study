def classify(text: str) -> tuple[str, int]:
    """問題文＋選択肢のテキストから分野コードを推定する。

    戻り値は (code, score)。score が 0 のときは判定できていない（X00）。
    長いキーワードほど強く効くようにし、問題文の冒頭に出た語は 1.5 倍に重み付けする。
    """
    if not text:
        return "X00", 0
    head = text[:140]
    best_code, best_score = "X00", 0
    for code, words in KEYWORDS.items():
        score = 0.0
        for w in words:
            if w in text:
                weight = len(w) * (1.5 if w in head else 1.0)
                score += weight
        if score > best_score:
            best_code, best_score = code, score
    return (best_code, int(best_score)) if best_score > 0 else ("X00", 0)


